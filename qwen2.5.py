from transformers import AutoModelForCausalLM, AutoTokenizer
import torch

# Choose the right model (Qwen2.5-0.5B-Instruct for lightweight testing)
model_name = "Qwen/Qwen2.5-0.5B-Instruct"

# Load tokenizer and model
tokenizer = AutoTokenizer.from_pretrained(model_name)
model = AutoModelForCausalLM.from_pretrained(
    model_name,
    device_map="auto",
    torch_dtype=torch.float16
)

# Keep track of conversation history
messages = [
    {"role": "system", "content": "You are a helpful assistant."}
]

def generate_reply(user_input: str):
    # Add user message to history
    messages.append({"role": "user", "content": user_input})

    # Format input with chat template
    inputs = tokenizer.apply_chat_template(
        messages,
        return_tensors="pt",
        add_generation_prompt=True  # ensures assistant reply
    ).to(model.device)

    attention_mask = torch.ones_like(inputs)

    outputs = model.generate(
        inputs,
        attention_mask=attention_mask,
        max_new_tokens=256,
        temperature=0.7,
        top_p=0.9
    )

    # Decode only new tokens (assistant's answer)
    generated_tokens = outputs[0][inputs.shape[-1]:]
    reply = tokenizer.decode(generated_tokens, skip_special_tokens=True).strip()

    # Save assistant reply to history
    messages.append({"role": "assistant", "content": reply})

    return reply

def chat():
    print("🤖 Qwen Chat (type 'exit' to quit)\n")
    while True:
        user_input = input("You: ")
        if user_input.lower() in ["exit", "quit"]:
            print("Goodbye! 👋")
            break

        reply = generate_reply(user_input)
        print(f"Assistant: {reply}\n")

if __name__ == "__main__":
    chat()

